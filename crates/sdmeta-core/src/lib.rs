//! # sdmeta-core
//!
//! SD Meta Editor の中核ライブラリ。GUI には一切依存しない。
//!
//! **現時点では実装は未着手。** 設計は以下を参照すること。
//!
//! - 要件定義書: `docs/requirements.md`
//! - 設計判断: `docs/adr/`
//!
//! ## 予定しているモジュール構成
//!
//! | モジュール | 責務 |
//! |---|---|
//! | `container` | JPEG / PNG / WebP のチャンク・セグメント走査とロスレス書き出し |
//! | `adapter`   | ツール別のキー → 正規フィールドへの写像（A1111 系、ComfyUI、NovelAI ほか） |
//! | `model`     | 正規フィールドモデル（要件定義書 FR-3） |
//! | `parser`    | 引用符対応トークナイザ（要件定義書 FR-4） |
//! | `preset`    | 削除プリセットの定義と適用（要件定義書 FR-5） |
//! | `stealth`   | アルファ LSB ステガノグラフィの検出・除去（ADR-0004） |
//! | `verify`    | 保存後の自己検証（要件定義書 FR-7） |
//!
//! ## 不変条件
//!
//! - 既定の書き出しパスで画素データをデコード・再エンコードしない
//! - 唯一の例外は stealth 除去時の PNG 再エンコード（ADR-0004）
//! - 未知のキー・チャンクも削除可能であること
//! - ICC プロファイルと EXIF Orientation は常に保持する